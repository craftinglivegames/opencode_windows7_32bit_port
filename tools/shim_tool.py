#!/usr/bin/env python3
"""Windows 7 import shim tooling for the Bun based opencode.exe.

Two steps:

1. ``gen_defs``  - read the import table of the host executable and emit two
   module definition files:

     * ``ocshim32.def`` - replaces the KERNEL32.dll import descriptor.  Every
       kernel32 function the host needs is re-exported: functions that exist on
       Windows 7 become PE forwarders (``KERNEL32.Foo``), functions that only
       appeared in Windows 8/10 are mapped onto the real implementations in
       ``ocshim32.cpp``.
     * ``ocn.def`` - replaces the ntdll.dll import descriptor (and provides
       the api-ms-win-core-synch-l1-2-0 entries).

2. ``patch``  - rewrite the import descriptor names inside the executable so
   that the loader resolves them from our shim DLLs instead of the real
   system DLLs.
"""

import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pe_imports import parse  # noqa: E402

# ---------------------------------------------------------------------------
#  Windows 7 SP1 does not export these (they are Windows 8 / Windows 10 APIs)
# ---------------------------------------------------------------------------
KERNEL32_MISSING = {
    "CreateFile2": "ocshim_CreateFile2",
    "GetSystemTimePreciseAsFileTime": "ocshim_GetSystemTimePreciseAsFileTime",
    "GetThreadDescription": "ocshim_GetThreadDescription",
    "NeedCurrentDirectoryForExePathW": "ocshim_NeedCurrentDirectoryForExePathW",
    "GetCurrentThreadStackLimits": "ocshim_GetCurrentThreadStackLimits",
    "DiscardVirtualMemory": "ocshim_DiscardVirtualMemory",
    "GetTimeZoneInformationForYear": "ocshim_GetTimeZoneInformationForYear",
    "CreatePseudoConsole": "ocshim_CreatePseudoConsole",
    "ClosePseudoConsole": "ocshim_ClosePseudoConsole",
    "ResizePseudoConsole": "ocshim_ResizePseudoConsole",
    # Windows 8 synchronisation primitives, imported through the API set
    "WaitOnAddress": "ocshim_WaitOnAddress",
    "WakeByAddressAll": "ocshim_WakeByAddressAll",
    "WakeByAddressSingle": "ocshim_WakeByAddressSingle",
}

NTDLL_MISSING = {
    "RtlGetSystemTimePrecise": "ocshim_RtlGetSystemTimePrecise",
    "RtlWaitOnAddress": "ocshim_RtlWaitOnAddress",
    "RtlWakeAddressAll": "ocshim_RtlWakeAddressAll",
    "RtlWakeAddressSingle": "ocshim_RtlWakeAddressSingle",
}


def gen_defs(exe_path, outdir):
    imports, _ = parse(exe_path)
    by_dll = {dll.lower(): funcs for dll, funcs in imports}

    kernel = [f for f in by_dll.get("kernel32.dll", []) if not f.startswith("#")]
    ntdll = [f for f in by_dll.get("ntdll.dll", []) if not f.startswith("#")]

    lines = ["; generated by gen_defs.py - do not edit", "EXPORTS"]
    for fn in kernel:
        if fn in KERNEL32_MISSING:
            lines.append(f"    {fn}={KERNEL32_MISSING[fn]}")
        else:
            lines.append(f"    {fn}=KERNEL32.{fn}")
    # synchronisation primitives (imported through the api-ms-win-core-synch set)
    for fn in ("WaitOnAddress", "WakeByAddressAll", "WakeByAddressSingle"):
        lines.append(f"    {fn}={KERNEL32_MISSING[fn]}")
    shim32 = os.path.join(outdir, "ocshim32.def")
    with open(shim32, "w", encoding="ascii", newline="\r\n") as fh:
        fh.write("\n".join(lines) + "\n")

    lines = ["; generated by gen_defs.py - do not edit", "EXPORTS"]
    for fn in ntdll:
        if fn in NTDLL_MISSING:
            lines.append(f"    {fn}")  # implemented in ocn.cpp
        else:
            lines.append(f"    {fn}=ntdll.{fn}")
    ocn = os.path.join(outdir, "ocn.def")
    with open(ocn, "w", encoding="ascii", newline="\r\n") as fh:
        fh.write("\n".join(lines) + "\n")

    # The ntdll native entry points are not part of the SDK import library, so a
    # stand-in import library is generated for the linker to resolve the
    # "ntdll.X" forwarders against.  It is only used at link time - the loader
    # resolves the forwarders against the real ntdll.dll at runtime.
    fake = ["; generated by gen_defs.py - do not edit", "LIBRARY ntdll.dll", "EXPORTS"]
    for fn in ntdll:
        if fn in NTDLL_MISSING:
            continue  # implemented by the shim, not forwarded to ntdll
        fake.append(f"    {fn}")
    fake_def = os.path.join(outdir, "ntdll_stand_in.def")
    with open(fake_def, "w", encoding="ascii", newline="\r\n") as fh:
        fh.write("\n".join(fake) + "\n")

    # stand-in import library for ocshim32.dll so that the linker can resolve
    # the "ocshim32.*" forwarders of ocn.dll
    fake = ["; generated by gen_defs.py - do not edit", "LIBRARY ocshim32.dll", "EXPORTS"]
    for fn in NTDLL_MISSING:
        fake.append(f"    {fn}")
    fake_def = os.path.join(outdir, "ocshim32_stand_in.def")
    with open(fake_def, "w", encoding="ascii", newline="\r\n") as fh:
        fh.write("\n".join(fake) + "\n")


    print(f"kernel32 exports : {len(kernel)}")
    print(f"ntdll exports    : {len(ntdll)}")
    print(f"wrote {shim32}")
    print(f"wrote {ocn}")
    return shim32, ocn


# ---------------------------------------------------------------------------
#  PE import descriptor patching
# ---------------------------------------------------------------------------

def patch(exe_path, out_path, mapping):
    """Rewrite import descriptor DLL names.

    ``mapping`` maps the *lower case* original DLL name to the new name.
    The new name must not be longer than the original one (the null
    terminator of the original string is kept, the remaining bytes are
    harmless padding because the loader stops at the first null byte).
    """
    data = bytearray(open(exe_path, "rb").read())
    e_lfanew = struct.unpack_from("<I", data, 0x3C)[0]
    coff = e_lfanew + 4
    nsec, _, _, _, _, opt_size, _ = struct.unpack_from("<HHIIIHH", data, coff)
    opt = coff + 20
    magic = struct.unpack_from("<H", data, opt)[0]
    pe32plus = magic == 0x20B
    dd_offset = opt + (112 if pe32plus else 96)
    num_rva = struct.unpack_from("<I", data, opt + (108 if pe32plus else 92))[0]
    dd_offset += (num_rva - 16) * 8
    size_of_headers = struct.unpack_from("<I", data, opt + 60)[0]

    sections = []
    sec_off = opt + opt_size
    for i in range(nsec):
        base = sec_off + i * 40
        vsize, va, raw_size, raw = struct.unpack_from("<IIII", data, base + 8)
        sections.append({"vsize": vsize, "va": va, "raw": raw})

    def rva_to_off(rva):
        for s in sections:
            if s["va"] <= rva < s["va"] + s["vsize"]:
                return rva - s["va"] + s["raw"]
        if rva < size_of_headers:
            return rva
        raise ValueError(f"cannot map rva {rva:#x}")

    def read_cstr(off):
        end = data.index(b"\x00", off)
        return bytes(data[off:end]).decode("ascii", "replace"), end

    import_rva, import_size = struct.unpack_from("<II", data, dd_offset + 8)
    if not import_rva:
        raise SystemExit("no import directory")
    off = rva_to_off(import_rva)
    patched = []
    while True:
        ilt_rva, ts, fchain, name_rva, iat_rva = struct.unpack_from("<IIIII", data, off)
        if not any((ilt_rva, name_rva, iat_rva)):
            break
        name_off = rva_to_off(name_rva)
        name, end = read_cstr(name_off)
        key = name.lower()
        if key in mapping:
            new = mapping[key].encode("ascii")
            if len(new) > (end - name_off):
                raise SystemExit(f"replacement for {name} is too long")
            data[name_off : name_off + len(new)] = new
            data[name_off + len(new) : end] = b"\x00" * (end - name_off - len(new))
            patched.append((name, mapping[key]))
        off += 20

    if not patched:
        raise SystemExit("nothing patched - descriptor names not found")
    with open(out_path, "wb") as fh:
        fh.write(data)
    for old, new in patched:
        print(f"  {old} -> {new}")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "gen_defs":
        gen_defs(sys.argv[2], sys.argv[3])
    elif cmd == "patch":
        mode = sys.argv[4] if len(sys.argv) > 4 else "all"
        full = {
            "kernel32.dll": "ocshim32.dll",
            "ntdll.dll": "ocn.dll",
            "api-ms-win-core-synch-l1-2-0.dll": "ocshim32.dll",
        }
        if mode == "k32":
            mapping = {"kernel32.dll": "ocshim32.dll"}
        elif mode == "ntdll":
            mapping = {"ntdll.dll": "ocn.dll"}
        elif mode == "apiset":
            mapping = {"api-ms-win-core-synch-l1-2-0.dll": "ocshim32.dll"}
        else:
            mapping = full
        patch(sys.argv[2], sys.argv[3], mapping)
    else:
        raise SystemExit("usage: gen_defs.py gen_defs <exe> <outdir> | patch <exe> <out>")
